// Compiles the JSON Schemas into standalone validator code at build time, so the
// web app never needs `new Function` at runtime (our CSP has no 'unsafe-eval').
// Usage: node scripts/gen-validators.mjs [--check]
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "schemas");
const outFile = join(root, "src", "generated", "validators.js");

const ajv = new Ajv2020({ strict: true, allErrors: true, code: { source: true, esm: true } });
for (const f of readdirSync(schemaDir).filter((n) => n.endsWith(".schema.json")).sort()) {
  ajv.addSchema(JSON.parse(readFileSync(join(schemaDir, f), "utf8")));
}

const base = "https://fairclaim.dev/schemas/";
const exportsMap = {
  validateDispatchCheck: `${base}dispatch-check.json`,
  validateHandoffCheck: `${base}handoff-check.json`,
  validateChallengeCheck: `${base}challenge-check.json`,
  validateDamageCheck: `${base}damage-check.json`,
  validateReview: `${base}review.json`,
  validatePolicy: `${base}policy.json`,
  validateClaimEvidence: `${base}claim-evidence.json`,
  validateEngineDecision: `${base}engine-decision.json`,
};

// ajv's ESM output still uses require() for its runtime helpers; rewrite those
// to static imports so the file is valid ESM in browsers and Node.
const imports = [];
const body = standaloneCode(ajv, exportsMap).replace(
  /const (func\d+) = require\("ajv\/dist\/runtime\/([a-z0-9]+)"\)\.default;/g,
  (_, fn, mod) => {
    imports.push(`import ${fn}_mod from "ajv/dist/runtime/${mod}.js";\nconst ${fn} = ${fn}_mod.default ?? ${fn}_mod;`);
    return "";
  },
);
if (body.includes("require(")) throw new Error("unexpected require() left in generated validators");
const code = `// GENERATED by scripts/gen-validators.mjs — do not edit.\n/* eslint-disable */\n${imports.join("\n")}\n${body.replace(/^"use strict";/, "")}`;

if (process.argv.includes("--check")) {
  const current = readFileSync(outFile, "utf8");
  if (current !== code) {
    console.error("validators.js is stale — run `npm run gen`.");
    process.exit(1);
  }
  console.log("validators.js is up to date.");
} else {
  writeFileSync(outFile, code);
  console.log(`wrote ${outFile}`);
}
